def describe_schemas(root: Path) -> dict[str, list[dict[str, str]]]:
    import duckdb

    connection = duckdb.connect()
    connection.execute("SET enable_progress_bar=false")
    out: dict[str, list[dict[str, str]]] = {}
    targets = {
        "`nifty500/parquet/nifty500_YYYY.parquet` — NIFTY 500 adjusted OHLCV": sorted(
            (root / "nifty500" / "parquet").glob("*.parquet")
        )[-1:],
        "`nifty750/parquet/nifty750_YYYY.parquet` — VAJRA 750 supporting adjusted master": sorted(
            (root / "nifty750" / "parquet").glob("*.parquet")
        )[-1:],
        "`nifty500/membership/nifty500_daily_membership.parquet` — daily point-in-time membership": [
            root / "nifty500" / "membership" / "nifty500_daily_membership.parquet"
        ],
        "`nifty750/membership/vajra750_monthly_vajra_750_universe.parquet` — monthly universe": [
            root / "nifty750" / "membership" / "vajra750_monthly_vajra_750_universe.parquet"
        ],
        "`corporate_actions/corporate_actions_applied.parquet` — events applied to prices": [
            root / "corporate_actions" / "corporate_actions_applied.parquet"
        ],
        "`calendar/nse_trading_sessions.parquet` — trading calendar": [
            root / "calendar" / "nse_trading_sessions.parquet"
        ],
    }
    for label, files in targets.items():
        files = [f for f in files if f.is_file()]
        if not files:
            continue
        schema = connection.execute(
            f"DESCRIBE SELECT * FROM read_parquet('{str(files[0]).replace(chr(92), '/')}')"
        ).fetchall()
        columns = []
        for name, dtype, *_ in schema:
            units, meaning = COLUMN_NOTES.get(name, ("—", ""))
            columns.append({"name": name, "type": dtype, "units": units, "meaning": meaning})
        out[label] = columns
    return out


