def data_dictionary(manifest: dict[str, Any], schemas: dict[str, list[dict[str, str]]]) -> str:
    sections = []
    for name, columns in schemas.items():
        rows = [
            "| Column | Type | Units | Meaning |",
            "|---|---|---|---|",
        ]
        for column in columns:
            rows.append(
                f"| `{column['name']}` | {column['type']} | {column.get('units', '—')} | "
                f"{column.get('meaning', '')} |"
            )
        sections.append(f"## {name}\n\n" + "\n".join(rows))
    body = "\n\n".join(sections)
    return f"""# DATA DICTIONARY

*Generated on {manifest['generated_at_utc'][:19]}Z. Companion to `START_HERE_AI.md`, which
explains how to use the data; this file explains what each column is.*

Conventions that apply everywhere:

- Currency is **INR**. Prices are per share.
- `Date` is a calendar date with no time component and no timezone. All sessions are NSE
  trading days in IST.
- Missing text is `NULL`, never the empty string.
- A missing `(Date, ISIN)` row means the security did not trade that session. It does not mean
  zero volume.
- `ISIN` is the stable identity across renames. `Symbol` is the ticker on that date only.

{body}
"""


def write_all(
    root: Path,
    manifest: dict[str, Any],
    *,
    quality: dict[str, Any] | None = None,
    schemas: dict[str, list[dict[str, str]]] | None = None,
) -> list[str]:
    written: list[str] = []
    _atomic_text(root / "START_HERE_AI.md", start_here(manifest, quality))
    written.append("START_HERE_AI.md")
    if schemas is None:
        schemas = describe_schemas(root)
    _atomic_text(root / "DATA_DICTIONARY.md", data_dictionary(manifest, schemas))
    written.append("DATA_DICTIONARY.md")
    return written


