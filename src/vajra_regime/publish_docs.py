def _atomic_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    encoded = text.encode("utf-8")
    if path.is_file() and path.read_bytes() == encoded:
        return
    temporary = path.with_name(f".{path.name}.{uuid4().hex}.partial")
    temporary.write_bytes(encoded)
    os.replace(temporary, path)


def _year_table(universe: dict[str, Any]) -> str:
    lines = [
        "| Year | Label | Rows | Securities | Sessions | Coverage | Membership basis |",
        "|---|---|---:|---:|---:|---|---|",
    ]
    for row in universe["years"]:
        lines.append(
            f"| {row['year']} | **{row['label']}** | {row['rows']:,} | {row['symbols']:,} | "
            f"{row['sessions']} | {row['first_date']} → {row['last_date']} | "
            f"`{row['membership_basis']}` |"
        )
    return "\n".join(lines)


def _label_summary(universe: dict[str, Any]) -> str:
    safe = universe["backtest_safe_years"]
    partial = universe["partial_years"]
    only = universe["price_data_only_years"]

    def span(years: list[int]) -> str:
        if not years:
            return "none"
        if len(years) == 1:
            return str(years[0])
        return f"{min(years)}–{max(years)}"

    return (
        f"BACKTEST_SAFE {span(safe)} · PARTIAL {span(partial)} · PRICE_DATA_ONLY {span(only)}"
    )


def _headline_table(n500: dict[str, Any], n750: dict[str, Any]) -> str:
    lines = [
        "| Universe | Rows | Securities ever present | Coverage | Year labels |",
        "|---|---:|---:|---|---|",
    ]
    for name, entry in (("nifty500", n500), ("nifty750", n750)):
        lines.append(
            f"| `{name}/` | {entry['rows']:,} | {entry['distinct_symbols']:,} "
            f"| {entry['first_date']} → {entry['last_date']} "
            f"| {_label_summary(entry)} |"
        )
    return "\n".join(lines)


